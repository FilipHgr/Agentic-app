/** Dlaždice v okně `windowName` s `gameCount` hrami ve „Vše“ před #156. */
export function tileBefore156(windowName: string, gameCount: number): TileBefore156 {
  const row = ROWS[windowName]?.[gameCount - 1];
  if (row === undefined) {
    throw new Error(`tabulka před #156 nemá okno ${windowName} s ${gameCount} hrami`);
  }
  const [columns, width, height, maxOffset, left, top, image, gap] = row;
  return { columns, width, height, maxOffset, left, top, image, gap };
}
