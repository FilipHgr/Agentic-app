/** Data záznamu alba, jak je fotoaparát uložil. */
export function legacyAlbumRecord(): RecordData {
  const hex = LEGACY_ALBUM_LAYER_HEX;
  const layer = new Uint8Array(hex.length / 2);
  for (let index = 0; index < layer.length; index += 1) {
    layer[index] = Number.parseInt(hex.slice(2 * index, 2 * index + 2), 16);
  }
  return {
    layerCode: 'p5',
    pictureId: 'house',
    pictureVersion: 1,
    layer,
  };
}

