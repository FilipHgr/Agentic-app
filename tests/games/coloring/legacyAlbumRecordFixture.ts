/** Barvy obrázku po pixelech (`null` bez barvy a na obrysu), jak je dítě vyfotilo. */
export function legacyAlbumPixels(): Array<number | null> {
  const pixels: Array<number | null> = [];
  for (const run of LEGACY_ALBUM_PIXEL_RUNS.split(' ')) {
    const empty = run.startsWith('-');
    const [color, count] = empty ? ['', run.slice(1)] : run.split('*');
    for (let step = 0; step < Number(count); step += 1) {
      pixels.push(empty ? null : Number(color));
    }
  }
  return pixels;
}
