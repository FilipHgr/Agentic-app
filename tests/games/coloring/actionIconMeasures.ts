/**
 * Změřené obrázky ikon pro #153 (ikony tlačítek alba a malování
 * z ElevenLabs): AC1 rozdíl obrázků aspoň 25 % a AC2 kontrast ikony proti
 * podkladu aspoň 3 : 1.
 *
 * Node ve Vitestu WebP nepřečte (projekt nemá dekodér, stejně jako
 * u obrázků map v Počítání, `tests/games/counting/mapPictureTones.ts`),
 * proto jsou obrázky změřené předem a `sha256` váže měření na soubor: když
 * se obrázek vymění, test otisku selže a obrázek se musí změřit znovu.
 * Ikony nástrojů (SVG Noto) si testy rasterizují samy (`maskOfSvg`).
 *
 * Mřížka `rows` (32 řádků shora, v řádku 32 dílků zleva oddělených
 * mezerou): obrázek zmenšený na 32 × 32 průměrem dílku s průhledností,
 * například
 *
 *   convert <soubor> -alpha on -filter Box -resize 32x32! txt:-
 *
 * Dílek s průhledností pod 50 % (alfa < 127,5) je `-`, jinak barva
 * `#RRGGBB` zaokrouhlená na celá čísla. Mřížka pokrývá celý čtverec, do
 * kterého hra ikonu kreslí (u WebP celý soubor).
 *
 * Okraj ikony `edgeColors` (jen u nových ikon, AC2): obrázek zmenšený na
 * 128 × 128 stejně jako výše; okrajový bod je bod s průhledností aspoň 50 %,
 * jehož soused (nahoře, dole, vlevo, vpravo) je průhledný nebo leží mimo
 * obrázek. Barva bodu (bez průhlednosti) se zaokrouhlí v každém kanálu na
 * nejbližší násobek 17 (`#RRGGBB` se zdvojenými číslicemi, např. `#33AA11`),
 * průhlednost `alpha` (0 až 1) se zaokrouhlí dolů na desetiny (bod je tak
 * v měření nejvýš tak sytý jako ve skutečnosti) a `share` je díl okrajových
 * bodů s touto barvou a průhledností. Vypisují se všechny dvojice barvy
 * a průhlednosti, i ty nejmenší. Test bod složí s průhledností na podklad
 * tlačítka (`actionButtonLook`) stejně, jak ho plátno hry nakreslí, a teprve
 * složenou barvu porovná s podkladem.
 *
 * Domeček, kolečko a Zpět kreslí hra kódem (Phaser), ne ze souboru; jejich
 * mřížka se změří ze snímku tlačítka ve WebKitu (symbol bez podkladu
 * vyříznutý na čtverec, do kterého ho hra kreslí) a `sha256` je `null`.
 * Při #153 byl k dispozici jen Chromium, mřížky jsou ze snímku v Chromiu
 * (iPad 1180 × 820, 2 obrazové body na CSS px): domeček a Zpět
 * v malování Omalovánek, kolečko v Počítání (v Omalovánkách není vidět),
 * barva symbolu je barva ve hře.
 * Až úkol mimo #153 symbol změní, změří se znovu v tom úkolu.
 */

/** Strana mřížky, ve které jsou obrázky změřené. */
export const MEASURE_GRID = 32;

export interface IconMeasure {
  /** Otisk souboru; `null` u symbolů kreslených kódem. */
  readonly sha256: string | null;
  /** `MEASURE_GRID` řádků po `MEASURE_GRID` dílcích: `-` nebo `#RRGGBB`. */
  readonly rows: readonly string[];
}

export interface EdgeColor {
  /** Barva okrajového bodu bez průhlednosti. */
  readonly color: string;
  /** Neprůhlednost bodu 0 až 1 (zaokrouhlená dolů na desetiny). */
  readonly alpha: number;
  readonly share: number;
}

export interface ActionIconMeasure extends IconMeasure {
  readonly sha256: string;
  /** Barvy okraje ikony a jejich díl (AC2 kontrast). */
  readonly edgeColors: readonly EdgeColor[];
}

