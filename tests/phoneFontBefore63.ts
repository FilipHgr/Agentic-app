/**
 * Dnešní písmo příkladu na telefonu v CSS px, zapsané před změnou
 * rozložení v #63 (příklad bez nikoho vedle). Hodnoty jsou vypočtené z kódu na
 * větvi sprint-3 v commitu 4dc5115 a jsou tu natvrdo, aby test
 * „písmo aspoň jako dnes“ porovnával s tím, co hráč viděl předtím,
 * a ne s tím, co spočítá nový kód.
 *
 * Na šířku (#54) závisí písmo na okně, rozsahu, ovládání a skupinkách teček
 * nápovědy (nápověda rozložení posouvá). Pořadí v `withHint` je pořadí
 * z `hintGroupsInRange`. Počet hvězdiček (i plná řada při oslavě) písmo
 * neměnil.
 *
 * Na výšku (#56) je místo pro nápovědu vyhrazené, písmo záviselo jen na
 * okně a rozsahu (stejné pro číselník i psaní a všechny druhy příkladů).
 */

import type { MaxNumber } from '../src/logic/settings';

export interface InputFonts {
  readonly withoutHint: number;
  readonly withHint: readonly number[];
}

export interface LandscapeFonts {
  readonly keypad: InputFonts;
  readonly writing: InputFonts;
}

type LandscapeWindowFonts = Readonly<Record<MaxNumber, LandscapeFonts>>;
type PortraitFonts = Readonly<Record<MaxNumber, number>>;

/**
 * Všechny různé skupinky teček nápovědy v rozsahu: jedna skupinka 1 až
 * rozsah (odčítání, sčítání s nulou) a dvě skupinky a + b ≤ rozsah.
 */
export function hintGroupsInRange(maxNumber: MaxNumber): number[][] {
  const groups: number[][] = [];
  for (let first = 1; first <= maxNumber; first += 1) {
    groups.push([first]);
  }
  for (let first = 1; first <= maxNumber; first += 1) {
    for (let second = 1; first + second <= maxNumber; second += 1) {
      groups.push([first, second]);
    }
  }
  return groups;
}

